-- Run once in Supabase Dashboard -> SQL Editor.
-- Phase 5 DOORSAFE vehicle flight recorder table.
create table if not exists public.vehicle_events (
  id bigint generated by default as identity primary key,
  local_event_id bigint,
  recorded_at timestamptz not null default now(),
  event_type text not null,
  source text not null,
  safety_state text,
  door_locked boolean,
  payload jsonb not null default '{}'::jsonb
);

create index if not exists vehicle_events_recorded_at_idx
  on public.vehicle_events (recorded_at desc);

alter table public.vehicle_events enable row level security;

-- This is deliberately limited to inserting/reading course-project telemetry
-- through the publishable key. Do not store personal information here.
create policy "course demo insert telemetry"
  on public.vehicle_events for insert to anon with check (true);

create policy "course demo read telemetry"
  on public.vehicle_events for select to anon using (true);
